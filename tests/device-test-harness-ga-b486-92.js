'use strict';
const fs=require('fs');
const assert=(v,m)=>{if(!v)throw new Error(m)};
const gameShared=fs.readFileSync('assets/shared/js/device-game-test-harness.js','utf8');
const game=fs.readFileSync('game/index.html','utf8');
const rootEntry=fs.readFileSync('index.html','utf8');
const studio=fs.readFileSync('studio/index.html','utf8');
const docs=fs.readFileSync('docs/index.html','utf8');
const aiIndex=JSON.parse(fs.readFileSync('AI_PROJECT_INDEX.json','utf8'));
const legacyShared='assets/shared/js/device-test-harness.js';
assert(!fs.existsSync(legacyShared),'retired shared legacy-capable harness must be physically removed');
assert(gameShared.includes("kind:'real_device_acceptance'"),'Formal Game report kind missing');
assert(gameShared.includes('navigator.serviceWorker.getRegistration'),'Formal Game service worker probe missing');
assert(gameShared.includes('../Export/skill/skills.json'),'Formal Game skill export probe missing');
assert(gameShared.includes('結果JSONをコピー'),'Formal Game clipboard fallback UI missing');
assert(gameShared.includes("['reactive','反応スキル'"),'Formal Game reactive manual case missing');
assert(!gameShared.includes('compileTaggedSkill'),'Formal Game harness retains compileTaggedSkill');
assert(!gameShared.includes('executeTaggedSkill'),'Formal Game harness retains executeTaggedSkill');
const build=JSON.parse(fs.readFileSync('package-build.json','utf8'));
const token=build.game_build.replace(/^GA-B486\./,'486');
assert(game.includes(`../assets/shared/js/device-game-test-harness.js?v=${token}`),'Formal Game harness ref missing');
assert(!game.includes('../assets/shared/js/device-test-harness.js'),'retired shared harness still loaded by Game');
const expectedEntrypoints=['index.html','game/index.html','studio/index.html'];
assert(JSON.stringify(build.public_entrypoints)===JSON.stringify(expectedEntrypoints),'package-build public entrypoints are not Formal-only');
assert(JSON.stringify(aiIndex.public_entrypoints)===JSON.stringify(expectedEntrypoints),'AI project index public entrypoints are not Formal-only');
const legacyLinkPattern=/href=["'][^"']*tag-test(?:\/|["'])/i;
for(const [label,text] of [['root',rootEntry],['game',game],['studio',studio],['docs',docs],['device harness',gameShared]]){
  assert(!legacyLinkPattern.test(text),`${label} still links a Legacy tag-test surface`);
}
