const assert=require('assert');
const fs=require('fs');
const vm=require('vm');
const registry=JSON.parse(fs.readFileSync('assets/shared/config/skill-registry.json','utf8'));
const compiler=require('../assets/shared/js/skill-compiler.js');
const sample={schemaVersion:1,id:'SKL-9530',name:'R05-D Formal Remove',trigger:{type:'ON_USE',scope:'SELF'},target:{side:'ALLY',range:'SINGLE'},effects:[{type:'REMOVE',category:'STATUS',count:1}],resource:{mpCost:0,cooldown:0}};
assert.strictEqual(compiler.VERSION,'FORMAL-SKILL-1');
const out=compiler.compileSkill(sample,registry);
assert.strictEqual(out.ok,true,JSON.stringify(out.errors));
assert.deepStrictEqual(out.compiledSkill.runtimeContracts.effectContracts,[{type:'REMOVE',category:'STATUS',count:1,all:false,order:'oldest'}]);
const events=[];
const ctx={console,battle:{tick:10,units:[],log:[]},recordValidationEvent:(type,payload)=>events.push({type,payload})};
vm.createContext(ctx);
vm.runInContext(fs.readFileSync('game/assets/js/tag-skill-runtime.js','utf8'),ctx);
const compiled=ctx.compileSkillForRuntime(out.compiledSkill);
assert.strictEqual(compiled.ok,true,JSON.stringify(compiled.errors));
const source={id:'S',name:'Source'};
const target={id:'T',name:'Target',alive:true,statusEffects:[{instanceId:'old',statusId:'A',appliedTick:1,expiresTick:100,removable:true},{instanceId:'new',statusId:'B',appliedTick:2,expiresTick:100,removable:true}]};
const result=ctx.executeRuntimeRemoveRuntime(source,target,compiled);
assert.strictEqual(result.removedCount,1);
assert.strictEqual(target.statusEffects[0].instanceId,'new');
assert.ok(events.some(x=>x.type==='skill_remove_executed'&&x.payload.count===1));
console.log('FORMAL_REMOVE_RUNTIME_R05_D_PASS');
