const fs=require('fs'),vm=require('vm');
const registry=JSON.parse(fs.readFileSync('assets/shared/config/skill-registry.json','utf8'));
const compiler=require('../assets/shared/js/skill-compiler.js');
function ok(v,m){if(!v)throw new Error(m)}
const path='game/assets/js/tag-skill-runtime.js';
const skill={schemaVersion:1,id:'E4B-SHIELD',name:'E4B Shield',trigger:{type:'ON_USE'},target:{side:'ALLY',range:'SINGLE'},effects:[{type:'APPLY',effectId:'BARRIER',power:100,duration:300}]};
const battle={tick:25,units:[],log:[]},ctx={console,battle};vm.createContext(ctx);vm.runInContext(fs.readFileSync(path,'utf8'),ctx);
ok(typeof ctx.applyShieldStackLifecycle==='function','SHIELD stack helper missing');
ok(typeof ctx.applyTaggedApplyRuntime==='function','Formal APPLY dispatcher missing');
const out=compiler.compileSkill(skill,registry);ok(out.ok,`Formal compile failed ${JSON.stringify(out.errors)}`);
const compiled=ctx.compileSkillForRuntime(out.compiledSkill);ok(compiled.ok,`Formal runtime compile failed ${JSON.stringify(compiled.errors)}`);
const contract=compiled.definition?.runtimeContracts?.applyContracts?.[0];
ok(contract?.logic==='SHIELD'&&contract?.effectId==='BARRIER','Formal SHIELD contract missing');
ok(contract?.values?.power===100&&contract?.values?.duration===300,'Formal SHIELD values mismatch');
const source={id:'SRC',name:'Source',alive:true},target={id:'TGT',name:'Target',alive:true,shieldEffects:[]};
const a=ctx.applyTaggedApplyRuntime(source,target,compiled,'SHIELD');
ok(a?.result?.ok,'Formal SHIELD first apply failed');
ok(a.result.policy?.stackRule==='STACK'&&a.result.policy?.effectiveRule==='SUM'&&a.result.policy?.consumeRule==='FIFO','Formal lifecycle policy not delegated');
const b=ctx.applyTaggedApplyRuntime(source,target,compiled,'SHIELD');
ok(b?.result?.ok&&target.shieldEffects.length===2,'Formal SHIELD second layer failed');
ok(ctx.shieldTotal(target)===200,'Formal SHIELD total mismatch');
ok(new Set(target.shieldEffects.map(x=>x.id)).size===2,'Formal SHIELD IDs not independent');
ok(target.shieldEffects.every(x=>x.amount===100&&x.remaining===100&&x.expiresAt===325),'Formal SHIELD layer snapshot changed');
ok(target.shieldEffects.every(x=>x.lifecyclePolicy?.consumeRule==='FIFO'),'Formal SHIELD lifecycle policy was not retained on layers');
const src=fs.readFileSync(path,'utf8');
ok(src.includes('applyTaggedShield(source,target,runtimeCompiled,lifecycleRef.formal?lifecycleRef.policy:null)'),'Production Formal SHIELD path does not delegate lifecycle policy');
console.log('FORMAL_SHIELD_RUNTIME_R03_E4B_PASS');
