const fs=require('fs');
const path=require('path');
const root=path.resolve(__dirname,'..');
const runtime=fs.readFileSync(path.join(root,'game/assets/js/app-runtime.js'),'utf8');
const compiler=require('../assets/shared/js/skill-compiler.js');
