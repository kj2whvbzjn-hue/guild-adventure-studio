'use strict';
const fs=require('fs');
const assert=require('assert');
const build=JSON.parse(fs.readFileSync('package-build.json','utf8'));
const html=fs.readFileSync('studio/index.html','utf8');
const policy=JSON.parse(fs.readFileSync('shared/integrity/test-integrity-policy.json','utf8'));
const systemPolicy=JSON.parse(fs.readFileSync('shared/integrity/system-file-policy.json','utf8'));
assert.strictEqual(build.studio_build,'GKS-B627');
assert.strictEqual(policy.baseline_policy_authoritative,true);
assert.strictEqual(policy.protection_scope_strategy,'union_baseline_and_applied_patterns');
assert.strictEqual(policy.new_protected_files_require_approval,true);
assert.strictEqual(policy.approval.external_only,true);
assert.strictEqual(policy.approval.packaged_approval_forbidden,true);
assert.strictEqual(policy.approval.runtime_human_confirmation_required,true);
assert(systemPolicy.classes.external_control.exact_paths.includes('TEST_CHANGE_APPROVAL.json'),'approval file must be an external-only control');
assert(!systemPolicy.rules.update_allowed_classes.includes('external_control'),'external approval must never be accepted inside SOURCE_UPDATE');
assert(html.includes('id="deployTestChangeApprovalFile"'),'Studio must have a separate external approval file input');
assert(html.includes("packageReader.entries.some(x=>x.path==='TEST_CHANGE_APPROVAL.json')"),'Studio must explicitly detect packaged approval metadata');
assert(html.includes('TEST_CHANGE_APPROVAL.jsonは更新ZIPへ同梱できません'),'Studio must reject packaged test-change approval');
assert(html.includes('validateStudioProtectedTestChanges(remote,files,[...studioDeployDeleteCandidates,...studioDeployDeleteBlocked])'),'Studio must validate protected add/modify/delete changes against GitHub HEAD');
assert(html.includes('loadStudioDeployBaselineTestIntegrityPolicy(remote,base)'),'Studio must load baseline Test Integrity policy from GitHub HEAD');
assert(html.includes('...baselinePatterns,...appliedPatterns'),'Studio must union baseline and applied protected patterns during the same update');
assert(html.includes('保護テスト/Gate変更の人間承認'),'Studio must require a separate human confirmation before deployment');
assert(html.includes('baseline_sha256')&&html.includes('updated_sha256'),'Studio must compare exact protected change hashes');
console.log('PASS GKS-B627 protected test/Gate changes require baseline+applied scope union, external exact-hash approval, add/modify/delete coverage, and separate deployment-time human confirmation');
