#!/usr/bin/env node
'use strict';
const assert = require('assert');
const fs = require('fs');
const path = require('path');
const Editor = require('../../studio/ai-production/ai-program-editor.js');
const base = {id:'AIP-0001',name:'Graph',status:'draft',nodes:[],edges:[],subroutines:[]};
const session = Editor.create(base);
const condition = session.addNode({id:'AIC-HP',node_type:'condition',data_version:'1.0.0'},{threshold:.5},{x:10,y:20});
const action = session.addNode({id:'AIA-HEAL',node_type:'action',data_version:'1.0.0'},{skill_id:'SKL-HEAL'},{x:240,y:20});
assert.strictEqual(condition.instance_id,'AIN-0001');
assert.strictEqual(action.instance_id,'AIN-0002');
assert.strictEqual(session.program().entry_node_id,'AIN-0001');
assert.strictEqual(session.program().nodes[0].master_data_version,'1.0.0');
const edge = session.connect({node_id:condition.instance_id,port_id:'true'},{node_id:action.instance_id,port_id:'in'});
assert.strictEqual(edge.edge_id,'AIE-0001');
assert.throws(()=>session.connect(edge.from,edge.to),/already exists/);
session.updateNode(action.instance_id,{position:{x:300,y:40},comment:'回復する',parameters:{skill_id:'SKL-HEAL-2'}});
assert.strictEqual(session.program().nodes[1].position.x,300);
assert.strictEqual(session.program().nodes[1].comment,'回復する');
assert.strictEqual(session.canUndo(),true);
assert.strictEqual(session.undo(),true);
assert.strictEqual(session.program().nodes[1].position.x,240);
assert.strictEqual(session.redo(),true);
assert.strictEqual(session.program().nodes[1].position.x,300);
const detached = session.program(); detached.nodes[0].position.x=999;
assert.strictEqual(session.program().nodes[0].position.x,10,'editor output must be isolated');
const root=path.resolve(__dirname,'../..');
const html=fs.readFileSync(path.join(root,'studio/index.html'),'utf8');
const ui=fs.readFileSync(path.join(root,'studio/ai-production/ai-production-ui.js'),'utf8');
const sw=fs.readFileSync(path.join(root,'studio/sw.js'),'utf8');
const manifest=JSON.parse(fs.readFileSync(path.join(root,'studio/ai-production/manifest.json'),'utf8'));
assert(html.includes('./ai-production/ai-program-editor.js?v=1'));
assert(html.includes('R5-B 構築編集'));
assert(sw.includes('./ai-production/ai-program-editor.js?v=1'));
assert.strictEqual(manifest.entrypoints.editor,'ai-program-editor.js');
assert(ui.includes('GKSAIProductionUI.addSelectedPart()'));
assert(ui.includes('GKSAIProductionUI.connectNodes()'));
assert(ui.includes('GKSAIProductionUI.undoGraph()'));
assert(!ui.includes('localStorage'));
const project={masters:{ai_conditions:[],ai_targets:[],ai_actions:[{id:'AIA-WAIT',name:'待機',status:'active',data_version:'1.0.0',evaluator:'action.wait',parameter_schema:{type:'object',properties:{}},ports:{inputs:[{id:'in'}],outputs:[{id:'next'}]}}],skills:[]},tags:[],ai_programs:[]};
global.GKSAIProductionHost={getData:()=>project,now:()=> '2026-08-11T23:00:00Z'};
const UI=require('../../studio/ai-production/ai-production-ui.js');
UI.newProgram(); UI.select('AIA-WAIT','action');
const placed=UI.addSelectedPart({querySelectorAll:()=>[]});
assert.strictEqual(placed.master_node_id,'AIA-WAIT');
assert.strictEqual(UI.isDirty(),true);
console.log('AI_PROGRAM_GRAPH_EDITOR_R5B_OK placement=1 connection=1 update=1 undo=1 redo=1 master_version=1 isolation=1');
