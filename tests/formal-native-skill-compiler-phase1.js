'use strict';
const fs=require('fs'),path=require('path'),assert=require('assert');
const root=path.join(__dirname,'..');
const compiler=require('../assets/shared/js/skill-native-compiler.js');
const registry=JSON.parse(fs.readFileSync(path.join(root,'assets/shared/config/skill-registry.json'),'utf8'));
assert(!JSON.stringify(registry).match(/legacy|generic/i),'formal Skill Registry contains migration terminology');
const sample={schemaVersion:1,id:'FORMAL-NATIVE-001',name:'正式Native複合',skillLevel:5,trigger:{type:'ON_USE',scope:'SELF'},conditions:[],target:{side:'ENEMY',range:'SINGLE'},effects:[{type:'DAMAGE',power:78,damageType:'PHYSICAL'},{type:'APPLY',effectId:'BURN',power:3,duration:20,interval:100,stackGain:1}],resource:{mpCost:0,cooldown:0,activationPriority:0}};
const out=compiler.compileSkill(sample,registry);
assert(out.ok,JSON.stringify(out.errors));
assert(out.compiledSkill.runtimeContracts);
assert(!('tags' in out.compiledSkill),'native compiled Skill must not contain tags');
assert(!('genericRuntime' in out.compiledSkill),'native compiled Skill must not contain genericRuntime');
assert(!('legacySkill' in out),'native compile result must not contain legacySkill');
assert(!('legacyValidation' in out),'native compile result must not contain legacyValidation');
const src=fs.readFileSync(path.join(root,'assets/shared/js/skill-native-compiler.js'),'utf8');
for(const token of ['legacySkill','legacyCompile','compileForLegacy','compileTaggedSkill','genericRuntime'])assert(!src.includes(token),`native compiler contains forbidden token: ${token}`);
console.log('FORMAL_NATIVE_SKILL_COMPILER_PHASE1_PASS');
