const assert=require('assert'),fs=require('fs'),vm=require('vm');
const registry=JSON.parse(fs.readFileSync('assets/shared/config/skill-generic-registry.json','utf8'));
const exportEnvelope=JSON.parse(fs.readFileSync('Export/skill/skills.json','utf8'));
const projectData=JSON.parse(fs.readFileSync('project-data.json','utf8'));
const build=JSON.parse(fs.readFileSync('package-build.json','utf8'));
const generic=require('../assets/shared/js/generic-skill-compiler.js');
const migration=require('../assets/shared/js/legacy-skill-migration.js');
const audit=require('../assets/shared/js/legacy-export-migration-audit.js');
function loadLegacy(path){const ctx={console};vm.createContext(ctx);vm.runInContext(fs.readFileSync(path,'utf8'),ctx);return ctx.compileTaggedSkill}
const before=JSON.stringify(projectData);
const report=audit.auditLegacyExport({exportEnvelope,projectData,currentGameBuild:build.game_build,currentStudioBuild:build.studio_build,migration,registry,legacyCompile:loadLegacy('game/assets/js/tag-skill-runtime.js'),genericCompile:generic.compileGenericSkill});
assert.strictEqual(audit.VERSION,'R06-C');
assert.strictEqual(report.mode,'READ_ONLY_AUDIT');
assert.strictEqual(JSON.stringify(projectData),before,'project-data.json object mutated during audit');
assert.strictEqual(report.summary.mutated,false);
assert.strictEqual(report.summary.total,95);
assert.strictEqual(report.summary.production_convertible,30);
assert.strictEqual(report.summary.production_blocked,15);
assert.strictEqual(report.summary.validation_only,33);
assert.strictEqual(report.summary.development_only,17);
assert.strictEqual(report.summary.promotion_candidates,30);
assert.strictEqual(report.summary.promotion_ready,0,'stale/test-like old export must not become current master data');
assert.strictEqual(report.summary.source_current,false);
assert.strictEqual(report.summary.project_master_skill_count,0);
assert.ok(report.items.filter(x=>x.environment!=='production').every(x=>!x.promotion_candidate));
assert.ok(report.items.filter(x=>x.environment==='production'&&!x.convertible).every(x=>!x.promotion_candidate));
assert.ok(report.items.filter(x=>x.promotion_candidate).every(x=>x.reasons.includes('SOURCE_NOT_CURRENT')));
console.log(`LEGACY_EXPORT_MIGRATION_AUDIT_R06_C_PASS total=${report.summary.total} candidate=${report.summary.promotion_candidates} ready=${report.summary.promotion_ready}`);
