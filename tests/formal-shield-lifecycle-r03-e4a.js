const fs=require('fs'),vm=require('vm');
const registry=JSON.parse(fs.readFileSync('assets/shared/config/skill-registry.json','utf8'));
const compiler=require('../assets/shared/js/skill-compiler.js');
function ok(v,m){if(!v)throw new Error(m)}
const path='game/assets/js/tag-skill-runtime.js';
const lifecycle=registry.effects?.BARRIER?.lifecycle;
const skill={schemaVersion:1,id:'E4A-SHIELD',name:'E4A Shield',trigger:{type:'ON_USE'},target:{side:'ALLY',range:'SINGLE'},effects:[{type:'APPLY',effectId:'BARRIER',power:100,duration:300}]};
const battle={tick:25,units:[],log:[]},ctx={console,battle};vm.createContext(ctx);vm.runInContext(fs.readFileSync(path,'utf8'),ctx);
ok(typeof ctx.compileSkillForRuntime==='function','Formal runtime compiler missing');
ok(typeof ctx.resolveShieldStackLifecyclePolicy==='function','SHIELD policy resolver missing');
ok(typeof ctx.applyShieldStackLifecycle==='function','SHIELD stack helper missing');
const good=ctx.resolveShieldStackLifecyclePolicy(lifecycle);ok(good.ok&&good.stackRule==='STACK'&&good.effectiveRule==='SUM'&&good.consumeRule==='FIFO','valid SHIELD lifecycle rejected');
const bad=ctx.resolveShieldStackLifecyclePolicy({...lifecycle,consumeRule:'LIFO'});ok(!bad.ok&&bad.field==='consumeRule','invalid SHIELD consume rule accepted');
const out=compiler.compileSkill(skill,registry);ok(out.ok,`Formal compile failed ${JSON.stringify(out.errors)}`);
const compiled=ctx.compileSkillForRuntime(out.compiledSkill);ok(compiled.ok,`Formal runtime compile failed ${JSON.stringify(compiled.errors)}`);
ok(compiled.definition?.runtimeContracts?.applyContracts?.[0]?.logic==='SHIELD','Formal SHIELD apply contract missing');
const source={id:'SRC',name:'Source',alive:true};
const helperTarget={id:'H',name:'Helper',alive:true,maxHp:100,shieldEffects:[]};
const h1=ctx.applyShieldStackLifecycle(helperTarget,{source,compiled,amount:100,duration:300},lifecycle);
const h2=ctx.applyShieldStackLifecycle(helperTarget,{source,compiled,amount:100,duration:300},lifecycle);
ok(h1.ok&&h2.ok&&helperTarget.shieldEffects.length===2,'helper did not retain independent shield layers');
ok(h2.totalShield===200&&ctx.shieldTotal(helperTarget)===200,'helper SUM total mismatch');
ok(helperTarget.shieldEffects[0].expiresAt===325&&helperTarget.shieldEffects[1].expiresAt===325,'helper expiry changed');
ok(helperTarget.shieldEffects.every(x=>x.amount===100&&x.remaining===100),'helper snapshot amount changed');
ok(new Set(helperTarget.shieldEffects.map(x=>x.id)).size===2,'helper shield IDs not independent');
// Production Formal route must delegate to the same registry lifecycle policy.
const runtimeTarget={id:'R',name:'Runtime',alive:true,maxHp:100,shieldEffects:[]};
const r1=ctx.applyTaggedApplyRuntime(source,runtimeTarget,compiled,'SHIELD');
const r2=ctx.applyTaggedApplyRuntime(source,runtimeTarget,compiled,'SHIELD');
ok(r1?.result?.ok&&r2?.result?.ok&&runtimeTarget.shieldEffects.length===2,'Formal runtime SHIELD layer count mismatch');
ok(r1.policy?.stackRule==='STACK'&&r1.policy?.effectiveRule==='SUM'&&r1.policy?.consumeRule==='FIFO','Formal runtime lifecycle policy mismatch');
ok(ctx.shieldTotal(runtimeTarget)===200,'Formal runtime shield total mismatch');
const shape=x=>({amount:x.amount,remaining:x.remaining,appliedAt:x.appliedAt,expiresAt:x.expiresAt,duration:x.duration,sourceId:x.sourceId,skillId:x.skillId});
ok(JSON.stringify(helperTarget.shieldEffects.map(shape))===JSON.stringify(runtimeTarget.shieldEffects.map(shape)),'helper/Formal runtime shield layer shape mismatch');
const srcText=fs.readFileSync(path,'utf8');
ok(srcText.includes('function applyShieldStackLifecycle'),'SHIELD lifecycle helper missing from Production runtime source');
ok(srcText.includes('lifecycleRef.formal?lifecycleRef.policy:null'),'Production Formal SHIELD route does not delegate lifecycle policy');
console.log('FORMAL_SHIELD_LIFECYCLE_R03_E4A_PASS');
